import * as React from 'react';
import { cva, type VariantProps } from 'class-variance-authority';
import { cn } from '@/lib/utils';

const badgeVariants = cva(
  'inline-flex items-center gap-1.5 rounded-full border px-3 py-0.5 text-xs font-semibold transition-colors focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2',
  {
    variants: {
      variant: {
        default:
          'border-transparent bg-primary text-primary-foreground shadow',
        gold:
          'border-gold-medium/30 bg-gold-medium/10 text-gold-bright uppercase tracking-[0.2em] text-[10px] sm:text-xs shadow-sm',
        'gold-subtle':
          'border-gold-medium/20 bg-navy-medium/90 text-gold-bright font-mono tracking-widest text-[10px] uppercase shadow-sm',
        'gold-solid':
          'border-gold-medium bg-gold-medium text-navy-dark font-bold uppercase tracking-widest text-[10px]',
        secondary:
          'border-transparent bg-secondary text-secondary-foreground',
        destructive:
          'border-transparent bg-destructive text-destructive-foreground',
        outline:
          'text-foreground border-border',
      },
    },
    defaultVariants: {
      variant: 'default',
    },
  }
);

export interface BadgeProps
  extends React.HTMLAttributes<HTMLDivElement>,
    VariantProps<typeof badgeVariants> {}

function Badge({ className, variant, ...props }: BadgeProps) {
  return (
    <div className={cn(badgeVariants({ variant }), className)} {...props} />
  );
}

export { Badge, badgeVariants };
